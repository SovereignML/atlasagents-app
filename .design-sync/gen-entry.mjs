// design-sync: regenerate the barrel entry from src/components/ui/*.tsx.
// Run after adding/removing a ui component, then update componentSrcMap in
// config.json to match. agent-plan exports `Plan` as default → aliased.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const uiDir = resolve(here, '../src/components/ui');
// Out-of-scope: marketing page *sections* (logo clouds, testimonials, feature
// grids), not reusable DS primitives. Deliberately excluded from the synced
// kit — keep in sync with componentSrcMap (34 primitives). (See NOTES.md.)
const EXCLUDE = new Set([
  'features-8', 'logo-cloud-2', 'team-showcase', 'testimonials-columns-1', 'trusted-companies',
]);
const files = readdirSync(uiDir)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => f.replace('.tsx', ''))
  .filter((f) => !EXCLUDE.has(f))
  .sort();
let out =
  '// design-sync: barrel entry for the SovereignML UI kit (esbuild → window.SovereignUI).\n' +
  '// Generated by .design-sync/gen-entry.mjs.\n' +
  'import "./process-shim";\n' +
  'export { ConsoleShell } from "./provider";\n';
for (const f of files) {
  out +=
    f === 'agent-plan'
      ? `export { default as AgentPlan } from "@/components/ui/${f}";\n`
      : `export * from "@/components/ui/${f}";\n`;
}
writeFileSync(resolve(here, 'entry.ts'), out);
console.error(`gen-entry: ${files.length} files`);
